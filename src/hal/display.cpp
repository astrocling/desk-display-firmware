esp_lcd_panel_io_handle_t s_panelIo = nullptr;
SemaphoreHandle_t s_transferDone = nullptr;
bool s_busInitialized = false;
bool s_panelReady = false;
uint32_t s_lastTransferTimeoutWarningMs = 0;
bool s_transferTimeoutWarningLogged = false;

int qspiCommand(uint32_t opcode, uint8_t command) {
  return static_cast<int>((opcode << 24) |
                          (static_cast<uint32_t>(command) << 8));
}

esp_err_t sendCommand(uint8_t command, const void* data, size_t dataSize) {
  return esp_lcd_panel_io_tx_param(
      s_panelIo, qspiCommand(kWriteCommandOpcode, command), data, dataSize);
}

bool onColorTransferDone(esp_lcd_panel_io_handle_t,
                         esp_lcd_panel_io_event_data_t*, void*) {
  BaseType_t higherPriorityTaskWoken = pdFALSE;
  xSemaphoreGiveFromISR(s_transferDone, &higherPriorityTaskWoken);
  return higherPriorityTaskWoken == pdTRUE;
}

void releasePanel() {
  s_panelReady = false;
  if (s_panelIo != nullptr) {
    esp_lcd_panel_io_del(s_panelIo);
    s_panelIo = nullptr;
  }
  if (s_busInitialized) {
    spi_bus_free(kLcdSpiHost);
    s_busInitialized = false;
  }
  if (s_transferDone != nullptr) {
    vSemaphoreDelete(s_transferDone);
    s_transferDone = nullptr;
  }
}

bool failInit(esp_err_t error) {
  Serial.printf("display: init failed (%s)\n", esp_err_to_name(error));
  displaySetBacklight(false);
  releasePanel();
  return false;
}

