void displaySetBacklight(bool on) {
  pinMode(pins::kLcdBl, OUTPUT);
  digitalWrite(pins::kLcdBl, on ? HIGH : LOW);
}

bool displayInit() {
  if (s_panelReady) {
    return true;
  }

  displaySetBacklight(false);

  spi_bus_config_t busConfig = {};
  busConfig.sclk_io_num = pins::kLcdPclk;
  busConfig.data0_io_num = pins::kLcdData0;
  busConfig.data1_io_num = pins::kLcdData1;
  busConfig.data2_io_num = pins::kLcdData2;
  busConfig.data3_io_num = pins::kLcdData3;
  busConfig.max_transfer_sz = kMaxTransferBytes;
  esp_err_t error =
      spi_bus_initialize(kLcdSpiHost, &busConfig, SPI_DMA_CH_AUTO);
  if (error != ESP_OK) {
    return failInit(error);
  }
  s_busInitialized = true;

  esp_lcd_panel_io_spi_config_t ioConfig = {};
  ioConfig.cs_gpio_num = pins::kLcdCs;
  ioConfig.dc_gpio_num = -1;
  ioConfig.spi_mode = 0;
  ioConfig.pclk_hz = 40 * 1000 * 1000;
  ioConfig.trans_queue_depth = 10;
  ioConfig.on_color_trans_done = onColorTransferDone;
  ioConfig.lcd_cmd_bits = 32;
  ioConfig.lcd_param_bits = 8;
  ioConfig.flags.quad_mode = true;
  // This SPI IO API has no byte-swap flag; LVGL must enable LV_COLOR_16_SWAP.
  s_transferDone = xSemaphoreCreateBinary();
  if (s_transferDone == nullptr) {
    return failInit(ESP_ERR_NO_MEM);
  }
  error = esp_lcd_new_panel_io_spi(
      static_cast<esp_lcd_spi_bus_handle_t>(kLcdSpiHost), &ioConfig,
      &s_panelIo);
  if (error != ESP_OK) {
    return failInit(error);
  }

  pinMode(pins::kLcdRst, OUTPUT);
  digitalWrite(pins::kLcdRst, HIGH);
  delay(100);
  digitalWrite(pins::kLcdRst, LOW);
  delay(120);
  digitalWrite(pins::kLcdRst, HIGH);
  delay(120);

  for (const InitCommand& command : kInitCommands) {
    error = sendCommand(command.command, command.data, command.dataSize);
    if (error != ESP_OK) {
      return failInit(error);
    }
    if (command.delayMs != 0) {
      delay(command.delayMs);
    }
  }

  s_panelReady = true;
  displaySetBacklight(true);
  Serial.println("display: ready");
  return true;
}

bool displayFlush(int x0, int y0, int x1, int y1, const uint16_t* pixels) {
  if (!s_panelReady || pixels == nullptr || x0 < 0 || y0 < 0 || x1 < x0 ||
      y1 < y0 || x1 >= kLcdWidth || y1 >= kLcdHeight) {
    return false;
  }

  const uint8_t columns[] = {static_cast<uint8_t>(x0 >> 8),
                             static_cast<uint8_t>(x0),
                             static_cast<uint8_t>(x1 >> 8),
                             static_cast<uint8_t>(x1)};
  const uint8_t rows[] = {static_cast<uint8_t>(y0 >> 8),
                          static_cast<uint8_t>(y0),
                          static_cast<uint8_t>(y1 >> 8),
                          static_cast<uint8_t>(y1)};
  esp_err_t error = sendCommand(0x2A, columns, sizeof(columns));
  if (error == ESP_OK) {
    error = sendCommand(0x2B, rows, sizeof(rows));
  }
  if (error == ESP_OK) {
    const size_t pixelBytes =
        static_cast<size_t>(x1 - x0 + 1) * (y1 - y0 + 1) * sizeof(uint16_t);
    error = esp_lcd_panel_io_tx_color(
        s_panelIo, qspiCommand(kWriteColorOpcode, 0x2C), pixels, pixelBytes);
  }
  if (error == ESP_OK &&
      xSemaphoreTake(s_transferDone, pdMS_TO_TICKS(kTransferTimeoutMs)) !=
          pdTRUE) {
    const uint32_t now = millis();
    if (!s_transferTimeoutWarningLogged ||
        now - s_lastTransferTimeoutWarningMs >= kWarningIntervalMs) {
      Serial.println("display: flush transfer timed out");
      s_lastTransferTimeoutWarningMs = now;
      s_transferTimeoutWarningLogged = true;
    }
    return false;
  }
  return error == ESP_OK;
}

